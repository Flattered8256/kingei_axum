CREATE TABLE "user" (
    id UUID PRIMARY KEY,
    username TEXT NOT NULL,
    email TEXT NOT NULL UNIQUE,
    created_at TIMESTAMPTZ NOT NULL,
    password_hash TEXT NOT NULL,
    avatar BIGINT
);

CREATE TABLE friend (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id UUID NOT NULL REFERENCES "user"(id),
    friend_id UUID NOT NULL REFERENCES "user"(id),
    created_at TIMESTAMPTZ NOT NULL,
    UNIQUE(user_id, friend_id)
);

CREATE TABLE friend_request (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sender_id UUID NOT NULL REFERENCES "user"(id),
    receiver_id UUID NOT NULL REFERENCES "user"(id),
    status TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL,
    UNIQUE(sender_id, receiver_id)
);

CREATE INDEX idx_friend_user_id ON friend(user_id);
CREATE INDEX idx_friend_request_receiver_id ON friend_request(receiver_id);
CREATE INDEX idx_friend_request_sender_id ON friend_request(sender_id);

CREATE TABLE chat (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    chat_type TEXT NOT NULL,
    name TEXT,
    owner_id UUID REFERENCES "user"(id),
    created_at TIMESTAMPTZ NOT NULL,
    avatar BIGINT
);

CREATE TABLE chat_member (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    chat_id BIGINT NOT NULL REFERENCES chat(id),
    user_id UUID NOT NULL REFERENCES "user"(id),
    created_at TIMESTAMPTZ NOT NULL,
    last_read_message_id BIGINT,
    UNIQUE(chat_id, user_id)
);

CREATE INDEX idx_chat_member_user_id ON chat_member(user_id);
CREATE INDEX idx_chat_member_chat_id ON chat_member(chat_id);

CREATE TABLE file (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_id UUID NOT NULL REFERENCES "user"(id),
    object_key TEXT NOT NULL UNIQUE,
    name TEXT NOT NULL,
    content_type TEXT NOT NULL,
    size BIGINT NOT NULL,
    status TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL
);

CREATE INDEX idx_file_owner_id ON file(owner_id);

ALTER TABLE "user"
    ADD CONSTRAINT user_avatar_fkey
    FOREIGN KEY (avatar) REFERENCES file(id) ON DELETE SET NULL;

CREATE INDEX idx_user_avatar ON "user"(avatar);

ALTER TABLE chat
    ADD CONSTRAINT chat_avatar_fkey
    FOREIGN KEY (avatar) REFERENCES file(id) ON DELETE SET NULL;

CREATE INDEX idx_chat_avatar ON chat(avatar);

CREATE TABLE message (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    chat_id BIGINT NOT NULL REFERENCES chat(id),
    sender_id UUID NOT NULL REFERENCES "user"(id),
    content TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL,
    file_id BIGINT REFERENCES file(id) ON DELETE SET NULL
);

CREATE INDEX idx_message_chat_id ON message(chat_id);
CREATE INDEX idx_message_chat_id_id ON message(chat_id, id);
CREATE INDEX idx_message_file_id ON message(file_id);

CREATE TABLE media (
    file_id BIGINT PRIMARY KEY REFERENCES file(id) ON DELETE CASCADE,
    kind TEXT NOT NULL,
    width BIGINT NOT NULL,
    height BIGINT NOT NULL,
    duration_ms BIGINT,
    thumbnail_id BIGINT REFERENCES file(id) ON DELETE SET NULL,
    created_at TIMESTAMPTZ NOT NULL
);

CREATE INDEX idx_media_thumbnail_id ON media(thumbnail_id);
